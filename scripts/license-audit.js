#!/usr/bin/env node
/**
 * License audit: for each image in EVENT_MEDIA, query Wikimedia Commons
 * for the file's license and flag anything that is not CC-BY / CC-BY-SA / PD.
 * Writes a report to docs/IMAGE-LICENSES.md
 */
const fs = require("fs");
const https = require("https");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const HTML = fs.readFileSync(path.join(ROOT, "timeline.html"), "utf8");

// Extract EVENT_MEDIA
const start = HTML.indexOf("const EVENT_MEDIA = {");
const end = HTML.indexOf("};", start) + 2;
const code = HTML.slice(start, end).replace("const EVENT_MEDIA", "var EVENT_MEDIA") + "\n return EVENT_MEDIA;";
const EVENT_MEDIA = new Function(code)();

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { "User-Agent": "cosmic-timeline-license-audit/1.0" } }, (res) => {
      let data = "";
      res.on("data", (c) => (data += c));
      res.on("end", () => {
        try { resolve(JSON.parse(data)); } catch (e) { reject(e); }
      });
    }).on("error", reject);
  });
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function auditFile(filename) {
  // filename like "the-big-bang.jpg" -> Commons file name "CMB_Timeline75.jpg" unknown; use the url's FilePath basename
  // We'll query by the url's filename portion
  const url = `https://commons.wikimedia.org/w/api.php?action=query&titles=File:${encodeURIComponent(filename)}&prop=imageinfo&iiprop=extmetadata&format=json`;
  try {
    const j = await fetchJson(url);
    const pages = j.query && j.query.pages;
    if (!pages) return { license: "unknown", note: "no pages" };
    const page = Object.values(pages)[0];
    const ii = page.imageinfo && page.imageinfo[0];
    const meta = ii && ii.extmetadata;
    const lic = meta && (meta.LicenseShortName || meta.License) && (meta.LicenseShortName.value || meta.License.value);
    return { license: lic || "unknown", artist: meta && meta.Artist && meta.Artist.value, credit: meta && meta.Credit && meta.Credit.value };
  } catch (e) {
    return { license: "error: " + e.message };
  }
}

(async () => {
  const rows = [];
  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "scripts", "image-manifest.json"), "utf8"));
  console.log("Auditing", manifest.length, "images via Commons API...");
  for (const m of manifest) {
    // extract Commons filename from URL
    // extract Commons filename from various URL formats
    let commonsName = null;
    const sp = m.url.match(/Special:FilePath\/([^?]+)/);
    if (sp) commonsName = decodeURIComponent(sp[1]);
    else {
      const thumb = m.url.match(/\/([^/]+\.jpg|[^/]+\.png|[^/]+\.svg|[^/]+\.jpeg)$/i);
      if (thumb) commonsName = decodeURIComponent(thumb[1]);
      else {
        const any = m.url.match(/\/([^/?]+\.(jpg|png|svg|jpeg))/i);
        if (any) commonsName = decodeURIComponent(any[1]);
      }
    }
    let license = "unknown";
    let artist = "";
    if (commonsName) {
      const apiUrl = `https://commons.wikimedia.org/w/api.php?action=query&titles=File:${encodeURIComponent(commonsName)}&prop=imageinfo&iiprop=extmetadata&format=json`;
      for (let attempt = 0; attempt < 3; attempt++) {
        try {
          const j = await fetchJson(apiUrl);
          const pages = j.query && j.query.pages;
          if (pages) {
            const page = Object.values(pages)[0];
            const ii = page.imageinfo && page.imageinfo[0];
            const meta = ii && ii.extmetadata;
            license = (meta && meta.LicenseShortName && meta.LicenseShortName.value) || (meta && meta.License && meta.License.value) || "unknown";
            artist = (meta && meta.Artist && meta.Artist.value) || "";
            break;
          }
        } catch (e) {
          license = "error: " + e.message;
          await sleep(2000);
        }
      }
    }
    rows.push({ title: m.title, file: m.filename, commons: commonsName, license, artist });
    await sleep(800);
  }
  // Write a report skeleton
  const flagged = rows.filter((r) => !/cc\s*by|public domain|\bpd\b/i.test(r.license));
  let md = "# Image license audit\n\n";
  md += "Generated by `scripts/license-audit.js` from `scripts/image-manifest.json`.\n\n";
  md += `Total images: ${rows.length}. Flagged (non CC-BY/PD): ${flagged.length}.\n\n`;
  md += "| Event | Local file | Commons file | License | Artist |\n|---|---|---|---|---|\n";
  rows.forEach((r) => { md += `| ${r.title} | ${r.file} | ${r.commons} | ${r.license} | ${r.artist.slice(0,60)} |\n`; });
  if (flagged.length) {
    md += "\n## Flagged (review manually)\n";
    flagged.forEach((r) => { md += `- ${r.title} (${r.file}): ${r.license}\n`; });
  }
  md += "\n## Notes\n";
  md += "- Full per-file license data lives in `scripts/image-manifest.json` (Commons URL per event).\n";
  md += "- Re-run with a Commons API key to fetch `LicenseShortName` for each original filename.\n";
  md += "- Policy: prefer CC-BY, CC-BY-SA, or public domain; flag any CC-BY-NC or commercial-restricted images.\n";
  fs.writeFileSync(path.join(ROOT, "docs", "IMAGE-LICENSES.md"), md);
  console.log("Wrote docs/IMAGE-LICENSES.md");
})();